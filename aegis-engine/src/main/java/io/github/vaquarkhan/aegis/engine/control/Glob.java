package io.github.vaquarkhan.aegis.engine.control;

/**
 * Linear-time glob matching ({@code *} = any sequence, {@code ?} = one character). No regular
 * expressions, so operator patterns cannot cause catastrophic backtracking.
 */
public final class Glob {

    private Glob() {}

    public static boolean matches(String pattern, String text) {
        int p = 0;
        int t = 0;
        int star = -1;
        int mark = 0;
        while (t < text.length()) {
            if (p < pattern.length() && (pattern.charAt(p) == '?' || pattern.charAt(p) == text.charAt(t))) {
                p++;
                t++;
            } else if (p < pattern.length() && pattern.charAt(p) == '*') {
                star = p++;
                mark = t;
            } else if (star >= 0) {
                p = star + 1;
                t = ++mark;
            } else {
                return false;
            }
        }
        while (p < pattern.length() && pattern.charAt(p) == '*') {
            p++;
        }
        return p == pattern.length();
    }

    public static boolean anyMatches(Iterable<String> patterns, String text) {
        for (String p : patterns) {
            if (matches(p, text)) {
                return true;
            }
        }
        return false;
    }
}
